/*
 * A tiny lowercase font: 6 x 8 pixels per letter, only the letters the
 * screen needs. Each glyph is drawn with '#' for ink and '.' for paper,
 * top row first, so you can read the font right here.
 */

`default_nettype none

module font (
    input  wire [7:0] char,     // ASCII code
    input  wire [2:0] row,      // 0..7, top to bottom
    input  wire [2:0] col,      // 0..7, left to right (6 and 7 are spacing)
    output wire       ink
);

  reg [8*6*8-1:0] glyph;        // 8 rows of 6 characters

  always @(*) begin
    case (char)
      "a": glyph = {"......", "......", ".####.", ".....#", ".#####", "#....#", ".#####", "......"};
      "b": glyph = {"#.....", "#.....", "#.###.", "##...#", "#....#", "##...#", "#.###.", "......"};
      "c": glyph = {"......", "......", ".####.", "#.....", "#.....", "#.....", ".####.", "......"};
      "d": glyph = {".....#", ".....#", ".###.#", "#...##", "#....#", "#...##", ".###.#", "......"};
      "e": glyph = {"......", "......", ".####.", "#....#", "######", "#.....", ".####.", "......"};
      "g": glyph = {"......", "......", ".#####", "#....#", "#....#", ".#####", ".....#", ".####."};
      "h": glyph = {"#.....", "#.....", "#.###.", "##...#", "#....#", "#....#", "#....#", "......"};
      "i": glyph = {"..#...", "......", ".##...", "..#...", "..#...", "..#...", ".###..", "......"};
      "k": glyph = {"#.....", "#.....", "#...#.", "#..#..", "###...", "#..#..", "#...#.", "......"};
      "l": glyph = {".##...", "..#...", "..#...", "..#...", "..#...", "..#...", ".###..", "......"};
      "m": glyph = {"......", "......", "##.##.", "#.#..#", "#.#..#", "#.#..#", "#.#..#", "......"};
      "n": glyph = {"......", "......", "#.###.", "##...#", "#....#", "#....#", "#....#", "......"};
      "o": glyph = {"......", "......", ".####.", "#....#", "#....#", "#....#", ".####.", "......"};
      "r": glyph = {"......", "......", "#.###.", "##...#", "#.....", "#.....", "#.....", "......"};
      "s": glyph = {"......", "......", ".#####", "#.....", ".####.", ".....#", "#####.", "......"};
      "t": glyph = {"..#...", "..#...", ".####.", "..#...", "..#...", "..#...", "...##.", "......"};
      "y": glyph = {"......", "......", "#....#", "#....#", "#....#", ".#####", ".....#", ".####."};
      "f": glyph = {"..###.", ".#....", "####..", ".#....", ".#....", ".#....", ".#....", "......"};
      "p": glyph = {"......", "......", "#.###.", "##...#", "##...#", "#.###.", "#.....", "#....."};
      "u": glyph = {"......", "......", "#....#", "#....#", "#....#", "#...##", ".###.#", "......"};
      "w": glyph = {"......", "......", "#....#", "#....#", "#.##.#", "#.##.#", ".#..#.", "......"};
      "x": glyph = {"......", "......", "#....#", ".#..#.", "..##..", ".#..#.", "#....#", "......"};
      "0": glyph = {".####.", "#....#", "#...##", "#..#.#", "#.#..#", "##...#", ".####.", "......"};
      "1": glyph = {"..#...", ".##...", "..#...", "..#...", "..#...", "..#...", ".###..", "......"};
      "2": glyph = {".####.", "#....#", ".....#", "...##.", ".##...", "#.....", "######", "......"};
      "3": glyph = {".####.", "#....#", ".....#", "..###.", ".....#", "#....#", ".####.", "......"};
      "4": glyph = {"...##.", "..#.#.", ".#..#.", "#...#.", "######", "....#.", "....#.", "......"};
      "5": glyph = {"######", "#.....", "#####.", ".....#", ".....#", "#....#", ".####.", "......"};
      "6": glyph = {"..###.", ".#....", "#.....", "#####.", "#....#", "#....#", ".####.", "......"};
      "7": glyph = {"######", ".....#", "....#.", "...#..", "..#...", "..#...", "..#...", "......"};
      "8": glyph = {".####.", "#....#", "#....#", ".####.", "#....#", "#....#", ".####.", "......"};
      "9": glyph = {".####.", "#....#", "#....#", ".#####", ".....#", "....#.", ".###..", "......"};
      ":": glyph = {"......", "......", "..##..", "..##..", "......", "..##..", "..##..", "......"};
      ">": glyph = {"......", ".#....", "..#...", "...#..", "....#.", "...#..", "..#...", ".#...."};
      ".": glyph = {"......", "......", "......", "......", "......", ".##...", ".##...", "......"};
      default: glyph = {8{"......"}};
    endcase
  end

  // Pick the row (top row is in the highest bits), then the character in it.
  wire [8*6-1:0] row_text = glyph[8*6*(7 - row) +: 8*6];
  assign ink = (col < 3'd6) && (row_text[8*(5 - col) +: 8] == "#");

endmodule
