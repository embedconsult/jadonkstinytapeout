/*
 * A tiny font: 6 x 8 pixels per letter, and only the letters the screen
 * needs: the digits, ':', '>', the box names a..e, and "take" and "add".
 * Each glyph is drawn with '#' for ink and '.' for paper, top row first,
 * so you can read the font right here.
 *
 * Letters are numbered (not ASCII) to keep the lookup table small:
 *   0..9 are the digits themselves, 10 ':', 11 '>',
 *   12..16 'a'..'e', 17 'k', 18 't', 31 blank.
 * So a digit n is simply letter n, and box b is letter 12 + b.
 */

`default_nettype none

module font (
    input  wire [4:0] letter,   // letter number, see above
    input  wire [2:0] row,      // 0..7, top to bottom
    input  wire [2:0] col,      // 0..7, left to right (6 and 7 are spacing)
    output wire       ink
);

  reg [8*6*8-1:0] glyph;        // 8 rows of 6 characters

  always @(*) begin
    case (letter)
      5'd0:  glyph = {".####.", "#....#", "#...##", "#..#.#", "#.#..#", "##...#", ".####.", "......"};  // 0
      5'd1:  glyph = {"..#...", ".##...", "..#...", "..#...", "..#...", "..#...", ".###..", "......"};  // 1
      5'd2:  glyph = {".####.", "#....#", ".....#", "...##.", ".##...", "#.....", "######", "......"};  // 2
      5'd3:  glyph = {".####.", "#....#", ".....#", "..###.", ".....#", "#....#", ".####.", "......"};  // 3
      5'd4:  glyph = {"...##.", "..#.#.", ".#..#.", "#...#.", "######", "....#.", "....#.", "......"};  // 4
      5'd5:  glyph = {"######", "#.....", "#####.", ".....#", ".....#", "#....#", ".####.", "......"};  // 5
      5'd6:  glyph = {"..###.", ".#....", "#.....", "#####.", "#....#", "#....#", ".####.", "......"};  // 6
      5'd7:  glyph = {"######", ".....#", "....#.", "...#..", "..#...", "..#...", "..#...", "......"};  // 7
      5'd8:  glyph = {".####.", "#....#", "#....#", ".####.", "#....#", "#....#", ".####.", "......"};  // 8
      5'd9:  glyph = {".####.", "#....#", "#....#", ".#####", ".....#", "....#.", ".###..", "......"};  // 9
      5'd10: glyph = {"......", "......", "..##..", "..##..", "......", "..##..", "..##..", "......"};  // colon
      5'd11: glyph = {"......", ".#....", "..#...", "...#..", "....#.", "...#..", "..#...", ".#...."};  // arrow
      5'd12: glyph = {"......", "......", ".####.", ".....#", ".#####", "#....#", ".#####", "......"};  // a
      5'd13: glyph = {"#.....", "#.....", "#.###.", "##...#", "#....#", "##...#", "#.###.", "......"};  // b
      5'd14: glyph = {"......", "......", ".####.", "#.....", "#.....", "#.....", ".####.", "......"};  // c
      5'd15: glyph = {".....#", ".....#", ".###.#", "#...##", "#....#", "#...##", ".###.#", "......"};  // d
      5'd16: glyph = {"......", "......", ".####.", "#....#", "######", "#.....", ".####.", "......"};  // e
      5'd17: glyph = {"#.....", "#.....", "#...#.", "#..#..", "###...", "#..#..", "#...#.", "......"};  // k
      5'd18: glyph = {"..#...", "..#...", ".####.", "..#...", "..#...", "..#...", "...##.", "......"};  // t
      default: glyph = {8{"......"}};  // blank
    endcase
  end

  // Pick the row (top row is in the highest bits), then the character in it.
  wire [8*6-1:0] row_text = glyph[8*6*(7 - row) +: 8*6];
  assign ink = (col < 3'd6) && (row_text[8*(5 - col) +: 8] == "#");

endmodule
